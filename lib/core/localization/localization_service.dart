  static Future<void> init() async {
    try {
      final box = await Hive.openBox('settings');
      final savedLang = box.get('app_lang', defaultValue: 'uz') as String;
      if (['uz', 'en', 'ru'].contains(savedLang)) {
        langNotifier.value = savedLang;
      }
    } catch (e) {
      debugPrint('Hive not initialized or offline in init: $e');
    }

    // If a user is already signed in on startup, sync preference with Firebase
    try {
      if (Firebase.apps.isNotEmpty) {
        final currentUser = FirebaseAuth.instance.currentUser;
        if (currentUser != null) {
          await syncUserLanguage(currentUser.uid);
        }
      }
    } catch (e) {
      debugPrint('FirebaseAuth/Firestore not initialized or offline in init: $e');
    }
  }

  static Future<void> changeLanguage(String langCode, {String? userId}) async {
    if (!['uz', 'en', 'ru'].contains(langCode)) return;

    langNotifier.value = langCode;

    // 1. Save locally to Hive
    try {
      final box = await Hive.openBox('settings');
      await box.put('app_lang', langCode);
    } catch (e) {
      debugPrint('Hive not initialized or offline in changeLanguage: $e');
    }

    // 2. Persist to Firebase Firestore if user is authenticated
    try {
      if (Firebase.apps.isNotEmpty) {
        final uid = userId ?? FirebaseAuth.instance.currentUser?.uid;
        if (uid != null && uid.isNotEmpty) {
          await FirebaseFirestore.instance.collection('users').doc(uid).set({
            'preferredLanguage': langCode,
            'lastLanguageUpdate': FieldValue.serverTimestamp(),
          }, SetOptions(merge: true));
        }
      }
    } catch (e) {
      // Offline or permissions failure is handled gracefully
      debugPrint('Error syncing language to Firestore: $e');
    }
  }

  /// Synchronize user's language preference from Firestore upon login or app start
  static Future<void> syncUserLanguage(String uid) async {
    try {
      final doc = await FirebaseFirestore.instance
          .collection('users')
          .doc(uid)
          .get()
          .timeout(const Duration(seconds: 2));
      if (doc.exists) {
        final data = doc.data();
        final remoteLang = data?['preferredLanguage'] as String?;
        if (remoteLang != null &&
            ['uz', 'en', 'ru'].contains(remoteLang) &&
            remoteLang != langNotifier.value) {
          langNotifier.value = remoteLang;
          final box = await Hive.openBox('settings');
          await box.put('app_lang', remoteLang);
        } else if (remoteLang == null) {
          // If remote doesn't have preferredLanguage yet, write local preference
          await FirebaseFirestore.instance.collection('users').doc(uid).set({
            'preferredLanguage': langNotifier.value,
          }, SetOptions(merge: true));
        }
      }
    } catch (e) {
      debugPrint('Error loading user language from Firestore: $e');
    }
  }

  static String translate(String key, {Map<String, dynamic>? params}) {
    final lang = langNotifier.value;
    String text = _localizedValues[lang]?[key] ??
        _localizedValues['uz']?[key] ??
        _localizedValues['en']?[key] ??
        key;

    if (params != null && params.isNotEmpty) {
      params.forEach((placeholder, value) {
        text = text.replaceAll('{$placeholder}', value.toString());
      });
    }

    return text;
  }

  /// ICU-compliant Pluralization support for Russian, Uzbek, and English
  static String plural(String keyPrefix, int count,
      {Map<String, dynamic>? params}) {
    final lang = langNotifier.value;
    String suffix = 'other';

    if (lang == 'ru') {
      final mod10 = count % 10;
      final mod100 = count % 100;
      if (mod10 == 1 && mod100 != 11) {
        suffix = 'one';
      } else if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) {
        suffix = 'few';
      } else {
        suffix = 'many';
      }
    } else if (lang == 'en') {
      suffix = count == 1 ? 'one' : 'other';
    } else {
      // Uzbek
      suffix = count == 1 ? 'one' : 'other';
    }

    final fullKey = '${keyPrefix}_$suffix';
    final mergedParams = <String, dynamic>{
      'count': count.toString(),
      ...?params,
    };

    // If specific plural form not found, fallback to _other or base key
    final candidate = _localizedValues[lang]?[fullKey] ??
        _localizedValues[lang]?['${keyPrefix}_other'] ??
        _localizedValues[lang]?[keyPrefix];

    if (candidate != null) {
      String text = candidate;
      mergedParams.forEach((placeholder, value) {
        text = text.replaceAll('{$placeholder}', value.toString());
      });
      return text;
    }

    return translate(keyPrefix, params: mergedParams);
  }

  /// Formats comments count using pluralization rules (e.g. "1 comment", "5 comments", "5 ta izoh")
  static String formatCommentsCount(int count) {
    return plural('comments_count', count);
  }

  static String formatLastSeen(DateTime lastSeen) {
    final now = DateTime.now();
    final difference = now.difference(lastSeen);
    final lang = langNotifier.value;
    final timeStr = DateFormat('HH:mm').format(lastSeen);

    // If within the last 60 seconds
    if (difference.inSeconds >= 0 && difference.inSeconds < 60) {
      switch (lang) {
        case 'ru':
          return 'только что';
        case 'uz':
          return 'hozirgina';
        case 'en':
        default:
          return 'just now';
      }
    }

    final today = DateTime(now.year, now.month, now.day);
    final yesterday = today.subtract(const Duration(days: 1));
    final seenDate = DateTime(lastSeen.year, lastSeen.month, lastSeen.day);

    if (seenDate == today) {
      switch (lang) {
        case 'ru':
          return 'был(а) сегодня в $timeStr';
        case 'uz':
          return 'oxirgi faollik bugun $timeStr da';
        case 'en':
        default:
          return 'last seen today at $timeStr';
      }
    }

    if (seenDate == yesterday) {
      switch (lang) {
        case 'ru':
          return 'был(а) вчера в $timeStr';
        case 'uz':
          return 'oxirgi faollik kecha $timeStr da';
        case 'en':
        default:
          return 'last seen yesterday at $timeStr';
      }
    }

    // Within current year: show Day Month, Time
    if (lastSeen.year == now.year) {
      if (lang == 'ru') {
        const ruMonths = [
          '',
          'янв.',
          'февр.',
          'марта',
          'апр.',
          'мая',
          'июня',
          'июля',
          'авг.',
          'сент.',
          'окт.',
          'нояб.',
          'дек.'
        ];
        final monthStr = ruMonths[lastSeen.month];
        return 'был(а) ${lastSeen.day} $monthStr в $timeStr';
      } else if (lang == 'uz') {
        const uzMonths = [
          '',
          'yanvar',
          'fevral',
          'mart',
          'aprel',
          'may',
          'iyun',
          'iyul',
          'avgust',
          'sentabr',
          'oktabr',
          'noyabr',
          'dekabr'
        ];
        final monthStr = uzMonths[lastSeen.month];
        return 'oxirgi faollik ${lastSeen.day}-$monthStr $timeStr da';
      } else {
        const enMonths = [
          '',
          'Jan',
          'Feb',
          'Mar',
          'Apr',
          'May',
          'Jun',
          'Jul',
          'Aug',
          'Sep',
          'Oct',
          'Nov',
          'Dec'
        ];
        final monthStr = enMonths[lastSeen.month];
        return 'last seen $monthStr ${lastSeen.day} at $timeStr';
      }
    }

    // Different year: show DD.MM.YYYY, Time
    final dayStr = lastSeen.day.toString().padLeft(2, '0');
    final monthStr = lastSeen.month.toString().padLeft(2, '0');
    final dateStr = '$dayStr.$monthStr.${lastSeen.year}';
    switch (lang) {
      case 'ru':
        return 'был(а) $dateStr в $timeStr';
      case 'uz':
        return 'oxirgi faollik $dateStr $timeStr da';
      case 'en':
      default:
        return 'last seen $dateStr at $timeStr';
    }
  }

  static String formatError(dynamic error) {
    final errStr = error.toString().replaceAll('Exception: ', '').trim();
    return translate('error_with_param', params: {'error': errStr});
  }

  static String formatMessageDate(DateTime dateTime) {
    final now = DateTime.now();
    final today = DateTime(now.year, now.month, now.day);
    final yesterday = today.subtract(const Duration(days: 1));
    final msgDate = DateTime(dateTime.year, dateTime.month, dateTime.day);

    if (msgDate == today) {
      return translate('today');
    }
    if (msgDate == yesterday) {
      return translate('yesterday');
    }

    final lang = langNotifier.value;
    if (dateTime.year == now.year) {
      if (lang == 'ru') {
        const ruMonths = [
          '', 'янв.', 'февр.', 'марта', 'апр.', 'мая', 'июня',
          'июля', 'авг.', 'сент.', 'окт.', 'нояб.', 'дек.'
        ];
        return '${dateTime.day} ${ruMonths[dateTime.month]}';
      } else if (lang == 'uz') {
        const uzMonths = [
          '', 'yanvar', 'fevral', 'mart', 'aprel', 'may', 'iyun',
          'iyul', 'avgust', 'sentabr', 'oktabr', 'noyabr', 'dekabr'
        ];
        return '${dateTime.day}-$uzMonths[dateTime.month]';
      } else {
        const enMonths = [
          '', 'Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun',
          'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'
        ];
        return '${enMonths[dateTime.month]} ${dateTime.day}';
      }
    }

    final dayStr = dateTime.day.toString().padLeft(2, '0');
    final monthStr = dateTime.month.toString().padLeft(2, '0');
    return '$dayStr.$monthStr.${dateTime.year}';
  }
